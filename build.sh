#!/usr/bin/env bash
# Builds tuya_light.c4z, tuya_plug.c4z and tuya_bridge.c4z into dist/.
#
# Each driver is the .lua files of its source folders (see sources()), concatenated in filename order
# into drivers/<variant>/driver.lua, syntax-checked as Lua 5.1, stamped, and zipped with
# driver.xml and www/. A .c4z is a plain zip; no packager is needed for an unencrypted driver.
# Requires: luajit (or luac), zip, git
set -euo pipefail

cd "$(dirname "$0")"
VERSION=$(git rev-list --count HEAD 2>/dev/null || echo 1)
BUILD_DATE=$(date +"%m/%d/%Y %H:%M")
mkdir -p dist

check_lua() {
  if command -v luajit >/dev/null; then
    luajit -bl "$1" >/dev/null
  else
    luac -p "$1"
  fi
}

# Which source folders make up each driver.
sources() {
  case "$1" in
    light|plug) echo "src/common src/child src/$1" ;;
    bridge) echo "src/common src/bridge" ;;
  esac
}

for variant in light plug bridge; do
  dir="drivers/$variant"
  out="$dir/driver.lua"
  {
    echo "-- Tuya ${variant} driver for Control4."
    echo "-- AUTO-GENERATED by build.sh — edit src/ instead."
    echo '---@diagnostic disable: undefined-global'
    # Sort by basename so common and variant files interleave by number.
    for f in $(for d in $(sources "$variant"); do ls "$d"/*.lua; done | awk -F/ '{print $NF" "$0}' | sort | cut -d' ' -f2); do
      echo
      echo "-- ${f}"
      sed "s/^DRIVER_VERSION = .*/DRIVER_VERSION = '${VERSION}'/" "$f"
    done
  } > "$out"
  check_lua "$out"

  # Stamp a staging copy, so building never leaves driver.xml modified in git.
  stage=$(mktemp -d)
  cp -R "$dir/driver.xml" "$out" "$dir/www" "$stage/"
  sed -i '' "s|<modified>.*</modified>|<modified>${BUILD_DATE}</modified>|" "$stage/driver.xml"
  sed -i '' "s|<version>[^<]*</version>|<version>${VERSION}</version>|" "$stage/driver.xml"

  c4z="dist/tuya_${variant}.c4z"
  rm -f "$c4z"
  (cd "$stage" && zip -qr "$OLDPWD/$c4z" driver.xml driver.lua www)
  rm -rf "$stage"
  echo "built $c4z (version $VERSION, $(wc -l < "$out" | tr -d ' ') lines of Lua)"
done
